#!/usr/bin/env python3
"""Builds every Mesh logo asset from ONE geometry definition (run: python3 branding/make_logo.py).

The mark ("Handoff"): a disc sheared along a diagonal cut, with a pointer-shaped hole crossing the seam.
Something slides from here to there; the pointer is the thing that arrives. The pointer is a real hole in
the shape (not painted over it), so the same geometry works as a one-colour Android "themed" icon.

Needs: shapely, cairosvg, pillow (build-time only; nothing here ships in the app).
"""
import io
import math
import os

import cairosvg
from PIL import Image
from shapely import affinity
from shapely.geometry import Polygon, Point, box
from shapely.ops import unary_union

HERE = os.path.dirname(os.path.abspath(__file__))
INK, PAPER = "#0B0B0C", "#F4F4F5"
CANVAS = 512.0
SAFE = 33.0 / 108.0   # Android keeps important content inside a 66dp circle of the 108dp adaptive canvas

# ---- geometry (512 x 512 canvas, y down) ------------------------------------------------------
R = 170.0
CENTER = (256.0, 256.0)
SLIDE = (18.0, -30.0)           # how far the upper-left half slides (the lower-right half moves the opposite way)
POINTER = [(0, 0), (0, 260), (68, 203), (114, 307), (161, 286), (117, 187), (203, 187)]
POINTER_SCALE, POINTER_TIP = 0.62, (214.0, 158.0)


def build():
    disc = Point(*CENTER).buffer(R, resolution=64)
    # The cut runs "/" through the centre, along the line x + y = 512: the upper-left half is the part of the disc
    # on the x + y < 512 side. Each half-plane is a big triangle with that line as one edge.
    far = 2000
    ul_plane = Polygon([(512 - far, far), (512 + far, -far), (-far * 2, -far * 2)])
    lr_plane = Polygon([(512 - far, far), (512 + far, -far), (far * 3, far * 3)])
    ul = affinity.translate(disc.intersection(ul_plane), *SLIDE)
    lr = affinity.translate(disc.intersection(lr_plane), -SLIDE[0], -SLIDE[1])
    pointer = Polygon([(POINTER_TIP[0] + x * POINTER_SCALE, POINTER_TIP[1] + y * POINTER_SCALE) for x, y in POINTER])
    pointer = pointer.buffer(3, join_style=1)                                          # softly rounded corners
    return unary_union([ul.difference(pointer), lr.difference(pointer)])


def path_data(geom, transform=lambda x, y: (x, y), digits=2):
    parts = []
    for poly in (geom.geoms if hasattr(geom, "geoms") else [geom]):
        for ring in [poly.exterior, *poly.interiors]:
            pts = [transform(x, y) for x, y in ring.simplify(0.12).coords]
            parts.append("M" + " L".join(f"{x:.{digits}f} {y:.{digits}f}" for x, y in pts[:-1]) + " Z")
    return " ".join(parts)


def fit(geom, canvas, safe_radius_fraction):
    """Scale + translate so the whole mark sits inside the adaptive-icon safe circle."""
    far = max(Point(*CENTER).distance(Point(x, y)) for poly in (geom.geoms if hasattr(geom, "geoms") else [geom])
              for x, y in poly.exterior.coords)
    s = (canvas * safe_radius_fraction) / far
    c = canvas / 2
    return lambda x, y: ((x - CENTER[0]) * s + c, (y - CENTER[1]) * s + c), s


def svg(path, bg=None, color=PAPER, size=512):
    bg_rect = f'<rect width="512" height="512" fill="{bg}"/>' if bg else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="{size}" height="{size}">{bg_rect}'
            f'<path fill="{color}" fill-rule="evenodd" d="{path}"/></svg>')


def png(svg_text, size):
    return Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg_text.encode(), output_width=size, output_height=size))).convert("RGBA")


def vector_drawable(path, size_dp, viewport, color="#FFFFFF", name=""):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {name} Generated by branding/make_logo.py: edit that script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp"
    android:height="{size_dp}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
    <path
        android:fillColor="{color}"
        android:fillType="evenOdd"
        android:pathData="{path}" />
</vector>
'''


def main():
    mark = build()
    out = lambda *p: os.path.join(HERE, *p)
    os.makedirs(out("android", "res", "drawable"), exist_ok=True)
    os.makedirs(out("android", "res", "mipmap-anydpi-v26"), exist_ok=True)
    os.makedirs(out("android", "res", "values"), exist_ok=True)

    # master artwork
    master = path_data(mark)
    open(out("logo.svg"), "w").write(svg(master, bg=INK))
    open(out("mark.svg"), "w").write(svg(master))                                    # transparent, for light surfaces use INK fill
    open(out("mark-dark.svg"), "w").write(svg(master, color=INK))
    png(svg(master, bg=INK), 1024).save(out("logo-1024.png"))
    png(svg(master, bg=INK), 256).save(out("logo-256.png"))                          # used by the Linux .desktop entry
    png(svg(master), 512).save(out("mark-512.png"))

    # Android adaptive icon: 108dp canvas, everything inside the 66% safe circle so no launcher mask can clip it.
    tf, scale = fit(mark, 108.0, SAFE)
    adaptive = path_data(mark, tf, digits=2)
    open(out("android", "res", "drawable", "ic_launcher_foreground.xml"), "w").write(
        vector_drawable(adaptive, 108, 108, "#FFF4F4F5", "Mesh launcher icon, foreground."))
    open(out("android", "res", "drawable", "ic_launcher_monochrome.xml"), "w").write(
        vector_drawable(adaptive, 108, 108, "#FF000000", "Mesh launcher icon, themed (monochrome) layer."))
    open(out("android", "res", "values", "ic_launcher_background.xml"), "w").write(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">%s</color>\n</resources>\n' % INK)
    adaptive_xml = '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
'''
    for name in ("ic_launcher", "ic_launcher_round"):
        open(out("android", "res", "mipmap-anydpi-v26", name + ".xml"), "w").write(adaptive_xml)

    # status bar / notification icon: a white silhouette on a 24dp grid, filling more of the canvas
    tf24, _ = fit(mark, 24.0, 0.46)
    open(out("android", "res", "drawable", "ic_stat_mesh.xml"), "w").write(
        vector_drawable(path_data(mark, tf24, digits=2), 24, 24, "#FFFFFFFF", "Mesh notification icon."))

    # a preview sheet that shows how launchers will actually mask it
    sheet = Image.new("RGBA", (1180, 360), (22, 22, 25, 255))
    full = svg(path_data(mark, fit(mark, 512.0, SAFE)[0]), bg=INK)                   # as the adaptive layers compose
    x = 24
    for label, mask in (("circle", "circle"), ("squircle", "squircle"), ("rounded", "rounded"), ("square", "square")):
        tile = png(full, 240)
        m = Image.new("L", (240, 240), 0)
        from PIL import ImageDraw
        d = ImageDraw.Draw(m)
        {"circle": lambda: d.ellipse((0, 0, 239, 239), fill=255),
         "squircle": lambda: d.rounded_rectangle((0, 0, 239, 239), radius=84, fill=255),
         "rounded": lambda: d.rounded_rectangle((0, 0, 239, 239), radius=40, fill=255),
         "square": lambda: d.rectangle((0, 0, 239, 239), fill=255)}[mask]()
        tile.putalpha(m)
        sheet.paste(tile, (x, 24), tile)
        x += 270
    # themed (monochrome) preview: the foreground tinted like Android 13+ does
    tint = png(svg(path_data(mark, fit(mark, 512.0, SAFE)[0]), bg="#CFE0FF", color="#1B2A44"), 96)
    sheet.paste(tint, (24, 262), tint)
    small = png(full, 48)
    sheet.paste(small, (140, 286), small)
    sheet.save(out("launcher-preview.png"))
    print("area:", round(mark.area), "| pieces:", len(mark.geoms) if hasattr(mark, "geoms") else 1,
          "| adaptive scale:", round(scale, 3), "| path chars:", len(adaptive))


if __name__ == "__main__":
    main()
